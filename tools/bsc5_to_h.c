/*
 * bsc5_to_h.c: converts the Yale Bright Star Catalog, 5th revised edition
 * (Hoffleit & Warren 1991, CDS catalog V/50, file "catalog") into bsc5.h.
 *
 *   curl -sL https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz | gunzip > catalog
 *   cc -O2 -o bsc5_to_h tools/bsc5_to_h.c -lm && ./bsc5_to_h < catalog > src/bsc5.h
 *
 * or simply: make catalog
 *
 * Columns follow the CDS ReadMe (1-based, inclusive): HR 1-4, RA (J2000)
 * 76-83, Dec 84-90, V magnitude 103-107, B-V 110-114. Entries without a
 * position (a few novae and non-stellar objects) are skipped.
 */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Field at 1-based inclusive columns [a, b] as a number; returns 0 if blank. */
static int field(const char *line, int a, int b, double *out) {
    char buf[32];
    int n = b - a + 1, len = (int)strlen(line);
    if (len < b) return 0;
    memcpy(buf, line + a - 1, n);
    buf[n] = 0;
    char *end;
    double v = strtod(buf, &end);
    if (end == buf) return 0;
    *out = v;
    return 1;
}

int main(void) {
    char line[512];
    int count = 0;
    printf("/* bsc5.h: generated by tools/bsc5_to_h.c from the Yale Bright Star Catalog,\n"
           "   5th revised edition (Hoffleit & Warren 1991, CDS V/50). Do not edit.\n"
           "   Columns: HR number, RA and Dec (J2000, radians), V magnitude, B-V. */\n"
           "static const struct { int hr; float ra, dec, vmag, bv; } BSC5[] = {\n");
    while (fgets(line, sizeof line, stdin)) {
        double hr, rah, ram, ras, ded, dem, des, vmag, bv;
        if (!field(line, 1, 4, &hr) || !field(line, 76, 77, &rah) || !field(line, 78, 79, &ram) ||
            !field(line, 80, 83, &ras) || !field(line, 85, 86, &ded) || !field(line, 87, 88, &dem) ||
            !field(line, 89, 90, &des) || !field(line, 103, 107, &vmag))
            continue;
        if (!field(line, 110, 114, &bv)) bv = 0.6; /* a handful lack B-V: use a solar-like color */
        double ra = (rah + ram / 60 + ras / 3600) * M_PI / 12;
        double dec = (ded + dem / 60 + des / 3600) * M_PI / 180 * (line[83] == '-' ? -1 : 1);
        printf("    {%d, %.7ff, %.7ff, %.2ff, %.2ff},\n", (int)hr, ra, dec, vmag, bv);
        count++;
    }
    printf("};\n#define BSC5_COUNT %d\n", count);
    fprintf(stderr, "%d stars\n", count);
    return 0;
}
